#pragma once

// Final build: the system as deployed.
//
// Same behaviour as V3, with the measurement scaffolding gone. The ESP32
// samples, evaluates the rules locally, deep-sleeps between samples, and wakes
// the Pi only when a rule fires or when the daily heartbeat is due. The Pi
// boots, collects the backlog, photographs, logs and halts.
//
// The four measurement rungs (v0_baseline .. v3_deepsleep) are frozen: they
// produced the numbers in the report and must not change. This one is free to
// evolve, which is the whole reason it exists as a separate folder.

#define VARIANT_NAME "Final"

#define SAMPLE_INTERVAL_MS          60000
#define ADAPTIVE_INTERVAL           1
#define RULES_ON_ESP32              1
#define LIGHT_SLEEP_BETWEEN_SAMPLES 0
#define DEEP_SLEEP_BETWEEN_SAMPLES  1

#define ADAPTIVE_FAST_MS            60000
#define ADAPTIVE_SLOW_MS            600000
#define ADAPTIVE_SOIL_DELTA         20
#define ADAPTIVE_TEMP_DELTA         1.0f
#define ADAPTIVE_STABLE_SAMPLES     3

// Wake the Pi once a day even if no rule fires, so a quiet plant still produces
// a photograph and a node that has died is distinguishable from one that has
// nothing to say. One wake costs 92 J, 0.08 % of the daily total.
#define HEARTBEAT_MS                86400000

