#!/usr/bin/env bash
# Install one rung of the variant ladder. One command does the lot: firmware,
# Pi code, the monitoring service and the dashboard.
#
#   ./install.sh v1_duty                 everything
#   ./install.sh v1_duty --fw-only       firmware only
#   ./install.sh v1_duty --pi-only       Pi code only
#   ./install.sh v1_duty --no-flash      build the firmware but do not flash it
#   ./install.sh v1_duty --no-service    skip the monitoring unit
#   ./install.sh v1_duty --no-dashboard  skip the dashboard unit
#   ./install.sh --list                  show the variants
#   ./install.sh v1_duty --local         build and flash on this machine (the Pi)
#   ./install.sh v1_duty --pi user@host  target a different Pi
#
# Run it on the Pi and it notices: no SSH, no rsync, no copying.
#
# The ESP32 is wired to the Pi, not to this laptop, so the build happens here
# and only the binaries travel. esptool runs on the Pi at 115200 baud with
# --no-stub: this board's CP2102 fails to start the stub flasher at any baud,
# and the ROM loader is slower but reliable.
#
# The Pi's address is remembered in .pi-target, so a new network only needs
# setting once:
#
#   ./install.sh v1_duty --pi admin@192.168.1.42
#   PI=admin@192.168.1.42 ./install.sh v1_duty
#
# Override the rest with PI_DIR=~/plant, FW_DIR=~/plant/fw, BAUD=115200.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TARGET_FILE="$ROOT/.pi-target"

# Precedence: --pi flag, then PI=, then the remembered target, then the default.
PI="${PI:-}"
PI_DIR="${PI_DIR:-~/plant}"
FW_DIR="${FW_DIR:-~/plant/fw}"
BAUD="${BAUD:-115200}"
BUILD="$ROOT/firmware/build"

VARIANTS=(v0_baseline v1_duty v2_adaptive v3_deepsleep)

# esptool lives in a venv, not in the system python. A fresh checkout has no
# .venv yet, and the flash step runs before the Pi-code step that would create
# one, so look for an interpreter that already has esptool and only build a venv
# as a last resort. PI_DIR keeps its literal ~ in the variable, so expand it.
PI_DIR_ABS="${PI_DIR/#\~/$HOME}"

find_esptool_python() {
  local candidate
  for candidate in "$ROOT/.venv/bin/python" "$PI_DIR_ABS/.venv/bin/python"; do
    if [ -x "$candidate" ] && "$candidate" -c 'import esptool' 2>/dev/null; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done
  if python3 -c 'import esptool' 2>/dev/null; then
    printf 'python3\n'
    return 0
  fi
  return 1
}

# The rules live in config/configuration.txt, which is the file the spec names.
# V0 and V1 read it at runtime on the Pi. V2 and V3 evaluate rules on the ESP32,
# which cannot read the Pi's disk while the Pi is powered off, so for those the
# rules are baked into the firmware here. Changing them therefore needs
# ./install.sh, not just a service restart.
#
# Pushing them over UART instead was tried and does not work: the ESP32 is
# asleep almost all the time in V3, and tell_esp32() writes once without
# retrying, so the command is usually lost.
generate_rules() {
  local config="$ROOT/config/configuration.txt"
  local -a rules=()
  local line

  if [ ! -f "$config" ]; then
    echo "install: missing $config" >&2
    return 1
  fi

  while IFS= read -r line; do
    line="${line%$'\r'}"                     # strip a CR from a CRLF file
    line="${line#"${line%%[![:space:]]*}"}"   # strip leading whitespace
    case "$line" in
      [0-9]*:*) rules+=("$line") ;;
    esac
  done < "$config"

  if [ ${#rules[@]} -eq 0 ]; then
    echo "install: no rules found in $config" >&2
    return 1
  fi

  echo ""
  echo "// Generated by install.sh from config/configuration.txt. Do not edit."
  echo "#define RULES_TEXT \\"
  local i last=$(( ${#rules[@]} - 1 ))
  for i in "${!rules[@]}"; do
    if [ "$i" -lt "$last" ]; then
      printf '    "%s\\n" \\\n' "${rules[$i]}"
    else
      printf '    "%s\\n"\n' "${rules[$i]}"
    fi
  done
}

usage() {
  sed -n '2,28p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

list_variants() {
  echo "variants:"
  for v in "${VARIANTS[@]}"; do
    name="$(sed -n 's/^#define VARIANT_NAME "\(.*\)"/\1/p' "$ROOT/variants/$v/variant.h")"
    printf '  %-14s %s\n' "$v" "$name"
  done
}

VARIANT=""
FW_ONLY=0
PI_ONLY=0
NO_FLASH=0
SERVICE=1
DASHBOARD=1
NEED_PI=0
LOCAL=0

for arg in "$@"; do
  case "$arg" in
    --list)     list_variants; exit 0 ;;
    --fw-only)  FW_ONLY=1 ;;
    --pi-only)  PI_ONLY=1 ;;
    --no-flash) NO_FLASH=1 ;;
    --service)  SERVICE=1 ;;
    --no-service)   SERVICE=0 ;;
    --dashboard)    DASHBOARD=1 ;;
    --no-dashboard) DASHBOARD=0 ;;
    --pi)       NEED_PI=1 ;;
    --local)    LOCAL=1 ;;
    -h|--help)  usage; exit 0 ;;
    -*)         echo "unknown option: $arg" >&2; usage >&2; exit 1 ;;
    *)
        if [ "$NEED_PI" -eq 1 ]; then
            PI="$arg"
            NEED_PI=0
        else
            VARIANT="$arg"
        fi
        ;;
  esac
done

if [ -z "$VARIANT" ]; then
  usage >&2
  echo >&2
  list_variants >&2
  exit 1
fi

if [ "$NEED_PI" -eq 1 ]; then
  echo "--pi needs an address, for example --pi admin@192.168.1.42" >&2
  exit 1
fi

if [ -z "$PI" ] && [ -f "$TARGET_FILE" ]; then
  PI="$(cat "$TARGET_FILE")"
fi
PI="${PI:-admin@10.42.0.15}"

# Running on the Pi itself? Then there is nothing to copy and no SSH to make.
# Comparing the target against this machine's own addresses means the same
# command works from the laptop and from the Pi's console.
if [ "$LOCAL" -eq 0 ]; then
  target_host="${PI#*@}"
  target_addr="$(getent hosts "$target_host" 2>/dev/null | awk '{print $1; exit}')" ||
    target_addr=""
  if [ -n "$target_addr" ] &&
     ip -o addr show 2>/dev/null | awk '{print $4}' | cut -d/ -f1 |
       grep -qx "$target_addr"; then
    LOCAL=1
    echo "== $target_host is this machine, so building and flashing here"
  fi
fi

VDIR="$ROOT/variants/$VARIANT"
if [ ! -d "$VDIR" ]; then
  echo "no such variant: $VARIANT" >&2
  list_variants >&2
  exit 1
fi

if [ "$FW_ONLY" -eq 1 ] && [ "$PI_ONLY" -eq 1 ]; then
  echo "--fw-only and --pi-only are mutually exclusive" >&2
  exit 1
fi

# --- preflight --------------------------------------------------------------
if [ "$LOCAL" -eq 1 ]; then
  # Running on the Pi itself: no SSH, no rsync, everything is already here.
  PI_ABS="$ROOT"
  echo "== local mode: building and flashing on this machine"
else
if ! ssh -o BatchMode=yes -o ConnectTimeout=5 "$PI" true 2>/dev/null; then
  echo "cannot reach $PI over SSH." >&2
  echo "  On a new network the address changes. Set it once with:" >&2
  echo "    ./install.sh $VARIANT --pi user@address" >&2
  echo "  or copy your key over first:  ssh-copy-id $PI" >&2
  exit 1
fi

if [ "$PI" != "$(cat "$TARGET_FILE" 2>/dev/null)" ]; then
  printf '%s' "$PI" > "$TARGET_FILE"
  echo "== target: $PI (remembered in .pi-target)"
fi

# systemd does not expand ~, so the unit needs the real absolute path.
PI_ABS="$(ssh "$PI" "cd $PI_DIR && pwd")"
fi

# --- firmware ---------------------------------------------------------------
if [ "$PI_ONLY" -eq 0 ]; then
  echo "== firmware: $VARIANT"
  cp "$VDIR/variant.h" "$ROOT/firmware/main/variant.h"
  generate_rules >> "$ROOT/firmware/main/variant.h"

  # shellcheck disable=SC1091
  . "$ROOT/tools/idf_env.sh"
  (cd "$ROOT/firmware" && idf.py build)

  if [ "$NO_FLASH" -eq 1 ]; then
    echo "== built, not flashing (--no-flash)"
  elif [ "$LOCAL" -eq 1 ]; then
    echo "== flashing locally on /dev/ttyUSB0"
    PY="$(find_esptool_python)" || {
      echo "== no python with esptool, creating $ROOT/.venv"
      python3 -m venv --system-site-packages "$ROOT/.venv"
      "$ROOT/.venv/bin/pip" install -q -r "$ROOT/requirements.txt"
      PY="$ROOT/.venv/bin/python"
    }
    "$PY" -m esptool \
        --port /dev/ttyUSB0 --baud "$BAUD" --no-stub write-flash \
        --flash-mode dio --flash-size 4MB --flash-freq 40m \
        0x1000 "$BUILD/bootloader/bootloader.bin" \
        0x8000 "$BUILD/partition_table/partition-table.bin" \
        0x10000 "$BUILD/plant_monitor.bin"
  else
    echo "== flashing on $PI"
    ssh "$PI" "mkdir -p $FW_DIR"
    scp -q "$BUILD/bootloader/bootloader.bin" \
           "$BUILD/partition_table/partition-table.bin" \
           "$BUILD/plant_monitor.bin" \
           "$PI:$FW_DIR/"
    ssh "$PI" "cd $FW_DIR && $PI_DIR/.venv/bin/python -m esptool \
        --port /dev/ttyUSB0 --baud $BAUD --no-stub write-flash \
        --flash-mode dio --flash-size 4MB --flash-freq 40m \
        0x1000 bootloader.bin 0x8000 partition-table.bin 0x10000 plant_monitor.bin"
  fi
fi

# --- Pi code ----------------------------------------------------------------
if [ "$FW_ONLY" -eq 0 ]; then
  echo "== pi code: $VARIANT"

  # The saliency model is not in the repository, so a fresh clone has no vision
  # until it is copied in. Warn here rather than letting every wake cycle log a
  # failure and halt.
  if [ ! -f "$ROOT/pi/vision/u2netp.onnx" ]; then
    echo "== warning: pi/vision/u2netp.onnx is missing, vision will fail"
    echo "   unzip leafs-starter.zip and copy u2netp.onnx into pi/vision/"
  fi

  if [ "$LOCAL" -eq 1 ]; then
    [ -d "$ROOT/.venv" ] || python3 -m venv --system-site-packages "$ROOT/.venv"
    "$ROOT/.venv/bin/pip" install -q -r "$ROOT/requirements.txt"
  else
  ssh "$PI" "mkdir -p $PI_DIR"

  # No --delete: the Pi also holds the venv, the logs and the flashed binaries,
  # and none of those live in this repo.
  rsync -az \
    --exclude '.git' --exclude '.venv' --exclude 'logs' --exclude 'fw' \
    --exclude '__pycache__' --exclude '*.pdf' --exclude '*.zip' \
    --exclude 'firmware/build' --exclude 'HANDOFF.md' \
    "$ROOT/" "$PI:$PI_DIR/"

  ssh "$PI" "cd $PI_DIR && \
    [ -d .venv ] || python3 -m venv --system-site-packages .venv; \
    .venv/bin/pip install -q -r requirements.txt"
  fi

  # Install a unit file. sudo over SSH has no terminal, so it only works
  # unattended when the Pi has passwordless sudo. Rather than embed a password
  # here, print the commands and let the user run them.
  install_unit() {
    local unit="$1" start="$2"
    if [ "$LOCAL" -eq 1 ]; then
      sudo mv "/tmp/$unit" "/etc/systemd/system/$unit" &&
        sudo systemctl daemon-reload &&
        sudo systemctl enable $start "$unit"
      echo "   installed and enabled"
      return
    fi
    scp -q "/tmp/$unit" "$PI:/tmp/$unit"
    if ssh "$PI" "sudo -n true" 2>/dev/null; then
      ssh "$PI" "sudo mv /tmp/$unit /etc/systemd/system/$unit && \
        sudo systemctl daemon-reload && sudo systemctl enable $start $unit"
      echo "   installed and enabled"
    else
      echo "   sudo needs a password on $PI, so run this yourself:"
      echo "     ssh $PI 'sudo mv /tmp/$unit /etc/systemd/system/$unit && \\"
      echo "       sudo systemctl daemon-reload && sudo systemctl enable $start $unit'"
    fi
  }

  if [ "$SERVICE" -eq 1 ]; then
    # One fixed unit name, so switching variants replaces the monitor instead
    # of leaving the previous one enabled and fighting for the camera.
    echo "== systemd unit: plant-monitor ($VARIANT)"
    UNIT="plant-monitor.service"
    printf '%s\n' \
      "[Unit]" \
      "Description=Smart plant monitor ($VARIANT)" \
      "After=multi-user.target" \
      "" \
      "[Service]" \
      "Type=simple" \
      "WorkingDirectory=$PI_ABS" \
      "ExecStart=$PI_ABS/.venv/bin/python $PI_ABS/tools/supervisor.py --variant $VARIANT" \
      "Restart=no" \
      "" \
      "[Install]" \
      "WantedBy=multi-user.target" \
      > "/tmp/$UNIT"
    install_unit "$UNIT" ""
  fi

  if [ "$DASHBOARD" -eq 1 ]; then
    echo "== systemd unit: plant-dashboard"
    UNIT="plant-dashboard.service"
    printf '%s\n' \
      "[Unit]" \
      "Description=Smart plant monitor dashboard" \
      "After=multi-user.target" \
      "" \
      "[Service]" \
      "Type=simple" \
      "WorkingDirectory=$PI_ABS" \
      "ExecStart=$PI_ABS/.venv/bin/python $PI_ABS/tools/dashboard.py" \
      "Restart=always" \
      "" \
      "[Install]" \
      "WantedBy=multi-user.target" \
      > "/tmp/$UNIT"
    install_unit "$UNIT" "--now"
    echo "   dashboard on http://<pi-address>:8081/"
  fi

  # Restart last, once every unit is in place. On V3 this is the moment the
  # node starts behaving like V3: the supervisor asks the ESP32 for its mode,
  # and the Pi halts after the first capture.
  if [ "$SERVICE" -eq 1 ]; then
    echo "== starting plant-monitor"
    if [ "$LOCAL" -eq 1 ]; then
      sudo systemctl restart plant-monitor.service
    else
      ssh "$PI" "sudo -n systemctl restart plant-monitor.service" 2>/dev/null ||
        echo "   restart it yourself: ssh $PI 'sudo systemctl restart plant-monitor'"
    fi
    if [ "$VARIANT" = "v3_deepsleep" ]; then
      echo "   V3 halts the Pi after the first capture. Press EN to wake it."
    fi
  fi
fi

echo
echo "== done: $VARIANT"
echo "   run on the Pi:  ssh $PI 'cd $PI_DIR && .venv/bin/python tools/supervisor.py --variant $VARIANT'"
